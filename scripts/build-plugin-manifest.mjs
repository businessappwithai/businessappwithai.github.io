#!/usr/bin/env node
/**
 * Writes plugin/manifest.js: the engine identity the plugin shows beside every
 * result — the language version and the SHA-256 of each published file it
 * runs. A JS module rather than JSON so the page can import it under a CSP that
 * allows no fetch at all.  `--check` fails when it is stale (CI runs that).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const FILES = ["guide/checker.js", "guide/fixer.js", "viewers/eml-model.js", "plugin/appwithai-eml.js", "plugin/app.js"];
const { LANGUAGE_VERSION } = await import(join(root, "guide/checker.js"));
const files = FILES.map((path) => ({ path, sha256: createHash("sha256").update(readFileSync(join(root, path))).digest("hex") }));
const body = `// Generated by scripts/build-plugin-manifest.mjs — do not edit.\nexport const MANIFEST = ${JSON.stringify({ languageVersion: LANGUAGE_VERSION, files }, null, 2)};\n`;
/* The widget's markup is index.html's <main>, so the ChatGPT panel and the
 * standalone page cannot drift apart. The MCP server imports it. */
const html = readFileSync(join(root, "plugin/index.html"), "utf8");
const main = html.slice(html.indexOf("<main>"), html.indexOf("</main>") + "</main>".length);
const widget = `// Generated by scripts/build-plugin-manifest.mjs from plugin/index.html — do not edit.\nexport const WIDGET_MAIN = ${JSON.stringify(main)};\n`;
const out = join(root, "plugin/manifest.js");
const widgetOut = join(root, "plugin/widget-markup.js");
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  let currentWidget = "";
  try { currentWidget = readFileSync(widgetOut, "utf8"); } catch {}
  if (currentWidget !== widget) { console.log("FAIL  plugin/widget-markup.js is stale. Rebuild: node scripts/build-plugin-manifest.mjs"); process.exit(1); }
  if (current !== body) { console.log("FAIL  plugin/manifest.js is stale. Rebuild: node scripts/build-plugin-manifest.mjs"); process.exit(1); }
  console.log("ok    plugin/manifest.js — up to date");
} else {
  writeFileSync(out, body);
  writeFileSync(widgetOut, widget);
  console.log("wrote plugin/manifest.js");
}
